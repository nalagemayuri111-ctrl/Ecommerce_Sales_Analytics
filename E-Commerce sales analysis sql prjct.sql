create database Eommerce_project;
use Eommerce_project;
CREATE TABLE customer_master (customer_id VARCHAR(20) PRIMARY KEY,customer_name VARCHAR(100),customer_age INT,
gender VARCHAR(20),customer_segment VARCHAR(50),customer_city VARCHAR(100),customer_state VARCHAR(100),
customer_country VARCHAR(100),region VARCHAR(50),customer_postal_code VARCHAR(20),customer_acquisition_cost DECIMAL(10,2));
CREATE TABLE product_catalog (product_id VARCHAR(20) PRIMARY KEY,product_name VARCHAR(255),product_category VARCHAR(100),
product_subcategory VARCHAR(100),brand VARCHAR(100),supplier VARCHAR(100),unit_price DECIMAL(10,2),
product_cost DECIMAL(10,2),product_rating DECIMAL(3,2));
CREATE TABLE order_items (order_id VARCHAR(20),product_id VARCHAR(20),quantity INT,unit_price DECIMAL(10,2),
discount_percentage DECIMAL(10,4),discount_amount DECIMAL(10,2),gross_sales DECIMAL(12,2),tax_amount DECIMAL(12,2),
shipping_cost DECIMAL(12,2),net_sales DECIMAL(12,2),product_cost DECIMAL(12,2),profit DECIMAL(12,2),
PRIMARY KEY (order_id, product_id),FOREIGN KEY (product_id) REFERENCES product_catalog(product_id));
